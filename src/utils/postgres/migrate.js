import { parseDefault, getFkColumnNames } from "../exportSQL/shared";
import { DB } from "../../data/constants";
import { normalizeCheckExpression, stripCheckWrapper } from "./checks";

function q(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

function columnTypeSql(field) {
  const size = field.size ? `(${field.size})` : "";
  const arr = field.isArray ? "[]" : "";
  return `${field.type}${size}${arr}`;
}

function normType(field) {
  return `${(field.type || "").toUpperCase()}|${field.size ?? ""}|${
    field.isArray ? "1" : "0"
  }`;
}

function normDefault(field) {
  const d = field.default;
  if (d === null || d === undefined) return "";
  return typeof d === "string" ? d.trim() : String(d).trim();
}

function checkClause(field) {
  const expression = stripCheckWrapper(field.check);
  if (!expression) return "";
  const name = String(field.checkName ?? "").trim();
  return ` ${name ? `CONSTRAINT ${q(name)} ` : ""}CHECK (${expression})`;
}

function columnDefinition(field, database) {
  let sql = columnTypeSql(field);
  if (field.increment) sql += " GENERATED BY DEFAULT AS IDENTITY";
  const def = normDefault(field);
  if (def) sql += ` DEFAULT ${parseDefault(field, database)}`;
  if (field.notNull) sql += " NOT NULL";
  if (field.unique) sql += " UNIQUE";
  sql += checkClause(field);
  return sql;
}

function uniqueCheckName(base, taken) {
  let candidate = base;
  let suffix = 2;
  while (taken.has(candidate)) {
    candidate = `${base}_${suffix}`;
    suffix += 1;
  }
  taken.add(candidate);
  return candidate;
}

/**
 * Checks for columns that already exist. New tables and new columns carry
 * their CHECK inline in CREATE TABLE / ADD COLUMN, so adding them again here
 * would create a duplicate constraint.
 */
function desiredCheckEntries(table, actualTable) {
  const existing = new Set((actualTable.fields ?? []).map((f) => f.name));
  const entries = [];
  for (const field of table.fields ?? []) {
    if (!existing.has(field.name)) continue;
    const expression = stripCheckWrapper(field.check);
    if (!expression) continue;
    entries.push({
      column: field.name,
      name: String(field.checkName ?? "").trim(),
      expression,
      normalized: normalizeCheckExpression(expression),
    });
  }
  return entries;
}

function constraintNameFor(catalog, tableName, columns) {
  const sig = columns.join(",");
  const match = (catalog.uniques ?? []).find(
    (u) => u.table === tableName && (u.columns ?? []).join(",") === sig,
  );
  return match?.name;
}

function columnSignature(cols) {
  return (cols ?? []).join(",");
}

function quoteList(cols) {
  return cols.map(q).join(", ");
}

function createTableSql(table, database) {
  const lines = table.fields.map(
    (f) => `\t${q(f.name)} ${columnDefinition(f, database)}`,
  );

  const pk = table.fields.filter((f) => f.primary).map((f) => f.name);
  if (pk.length) lines.push(`\tPRIMARY KEY (${quoteList(pk)})`);

  for (const uc of table.uniqueConstraints ?? []) {
    if (Array.isArray(uc.fields) && uc.fields.length > 0) {
      lines.push(`\tCONSTRAINT ${q(uc.name)} UNIQUE (${quoteList(uc.fields)})`);
    }
  }

  const inherits =
    Array.isArray(table.inherits) && table.inherits.length
      ? ` INHERITS (${table.inherits.map(q).join(", ")})`
      : "";

  return `CREATE TABLE IF NOT EXISTS ${q(table.name)} (\n${lines.join(",\n")}\n)${inherits};`;
}

function createEnumSql(e) {
  const values = (e.values ?? []).map(
    (v) => `'${String(v).replace(/'/g, "''")}'`,
  );
  return `CREATE TYPE ${q(e.name)} AS ENUM (${values.join(", ")});`;
}

function createTypeSql(type) {
  const fields = (type.fields ?? []).map((f) => `${q(f.name)} ${f.type}`);
  return `CREATE TYPE ${q(type.name)} AS (${fields.join(", ")});`;
}

function createIndexSql(tableName, index) {
  const cols = (index.fields ?? []).map(q).join(", ");
  return `CREATE ${index.unique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${q(
    index.name,
  )} ON ${q(tableName)} (${cols});`;
}

function fkSignature(schema, table, columns, refTable, refColumns) {
  return `${schema}.${table}(${columns.join(",")})->${refTable}(${refColumns.join(",")})`;
}

export function buildMigration(desired, actual, catalog, options = {}) {
  const database = DB.POSTGRES;
  const includeDrops = options.includeDrops !== false;
  const operations = [];
  let opId = 0;

  const push = (group, label, sql, destructive = false) => {
    if (!sql) return;
    operations.push({ id: opId++, group, label, sql, destructive });
  };

  const desiredTables = new Map((desired.tables ?? []).map((t) => [t.name, t]));
  const actualTables = new Map((actual.tables ?? []).map((t) => [t.name, t]));

  const desiredEnums = new Map((desired.enums ?? []).map((e) => [e.name, e]));
  const actualEnums = new Map((actual.enums ?? []).map((e) => [e.name, e]));

  const desiredTypes = new Map((desired.types ?? []).map((t) => [t.name, t]));
  const actualTypes = new Map((actual.types ?? []).map((t) => [t.name, t]));

  // ---- Enums ----
  for (const [name, e] of desiredEnums) {
    if (!actualEnums.has(name)) {
      push("enum", `create enum ${name}`, createEnumSql(e));
    } else {
      const actualValues = new Set(actualEnums.get(name).values ?? []);
      for (const v of e.values ?? []) {
        if (!actualValues.has(v)) {
          push(
            "enum",
            `add value ${name}.${v}`,
            `ALTER TYPE ${q(name)} ADD VALUE IF NOT EXISTS '${String(v).replace(/'/g, "''")}';`,
          );
        }
      }
    }
  }
  if (includeDrops) {
    for (const [name] of actualEnums) {
      if (!desiredEnums.has(name)) {
        push(
          "enum",
          `drop enum ${name}`,
          `DROP TYPE IF EXISTS ${q(name)};`,
          true,
        );
      }
    }
  }

  // ---- Composite types ----
  for (const [name, type] of desiredTypes) {
    if (!actualTypes.has(name)) {
      push("type", `create type ${name}`, createTypeSql(type));
    }
  }
  if (includeDrops) {
    for (const [name] of actualTypes) {
      if (!desiredTypes.has(name)) {
        push(
          "type",
          `drop type ${name}`,
          `DROP TYPE IF EXISTS ${q(name)};`,
          true,
        );
      }
    }
  }

  // ---- Tables: create missing ----
  for (const [name, table] of desiredTables) {
    if (!actualTables.has(name)) {
      push("table", `create table ${name}`, createTableSql(table, database));
      for (const index of table.indices ?? []) {
        push(
          "index",
          `create index ${index.name}`,
          createIndexSql(name, index),
        );
      }
    }
  }

  // ---- Tables: diff existing ----
  for (const [name, table] of desiredTables) {
    const actualTable = actualTables.get(name);
    if (!actualTable) continue;

    const actualCols = new Map(actualTable.fields.map((f) => [f.name, f]));

    // Columns
    for (const field of table.fields) {
      const ac = actualCols.get(field.name);
      if (!ac) {
        push(
          "column",
          `add column ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ADD COLUMN ${q(field.name)} ${columnDefinition(field, database)};`,
        );
        continue;
      }

      if (normType(field) !== normType(ac)) {
        const type = columnTypeSql(field);
        push(
          "column",
          `alter type ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ALTER COLUMN ${q(
            field.name,
          )} TYPE ${type} USING ${q(field.name)}::${type};`,
        );
      }

      if (field.notNull && !ac.notNull) {
        push(
          "column",
          `set not null ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ALTER COLUMN ${q(field.name)} SET NOT NULL;`,
        );
      } else if (!field.notNull && ac.notNull) {
        push(
          "column",
          `drop not null ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ALTER COLUMN ${q(field.name)} DROP NOT NULL;`,
        );
      }

      const wantDefault = normDefault(field);
      const hasDefault = normDefault(ac);
      if (wantDefault !== hasDefault) {
        if (wantDefault) {
          push(
            "column",
            `set default ${name}.${field.name}`,
            `ALTER TABLE ${q(name)} ALTER COLUMN ${q(
              field.name,
            )} SET DEFAULT ${parseDefault(field, database)};`,
          );
        } else {
          push(
            "column",
            `drop default ${name}.${field.name}`,
            `ALTER TABLE ${q(name)} ALTER COLUMN ${q(field.name)} DROP DEFAULT;`,
          );
        }
      }

      if (field.increment && !ac.increment) {
        push(
          "column",
          `add identity ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ALTER COLUMN ${q(
            field.name,
          )} ADD GENERATED BY DEFAULT AS IDENTITY;`,
        );
      } else if (!field.increment && ac.increment) {
        push(
          "column",
          `drop identity ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ALTER COLUMN ${q(
            field.name,
          )} DROP IDENTITY IF EXISTS;`,
        );
      }

      if (field.unique && !ac.unique) {
        const cname =
          constraintNameFor(catalog, name, [field.name]) ??
          `${name}_${field.name}_key`;
        push(
          "unique",
          `add unique ${name}.${field.name}`,
          `ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(cname)} UNIQUE (${q(
            field.name,
          )});`,
        );
      } else if (!field.unique && ac.unique) {
        const cname = constraintNameFor(catalog, name, [field.name]);
        if (cname) {
          push(
            "unique",
            `drop unique ${name}.${field.name}`,
            `ALTER TABLE ${q(name)} DROP CONSTRAINT IF EXISTS ${q(cname)};`,
            true,
          );
        }
      }
    }

    if (includeDrops) {
      for (const [colName] of actualCols) {
        if (!table.fields.some((f) => f.name === colName)) {
          push(
            "column",
            `drop column ${name}.${colName}`,
            `ALTER TABLE ${q(name)} DROP COLUMN IF EXISTS ${q(colName)};`,
            true,
          );
        }
      }
    }

    // Primary key
    const desiredPk = table.fields.filter((f) => f.primary).map((f) => f.name);
    const actualPkMeta = (catalog.primaryKeys ?? []).find(
      (pk) => pk.table === name,
    );
    const actualPk = actualPkMeta?.columns ?? [];
    const pkChanged =
      desiredPk.length !== actualPk.length ||
      desiredPk.some((c, i) => c !== actualPk[i]);
    if (pkChanged) {
      if (actualPkMeta?.name) {
        push(
          "primary_key",
          `drop primary key ${name}`,
          `ALTER TABLE ${q(name)} DROP CONSTRAINT IF EXISTS ${q(
            actualPkMeta.name,
          )};`,
          true,
        );
      }
      if (desiredPk.length) {
        push(
          "primary_key",
          `add primary key ${name}`,
          `ALTER TABLE ${q(name)} ADD PRIMARY KEY (${quoteList(desiredPk)});`,
        );
      }
    }

    // Multi-column unique constraints
    const desiredUniques = (table.uniqueConstraints ?? []).filter(
      (uc) => (uc.fields ?? []).length > 1,
    );
    const actualUniques = (actualTable.uniqueConstraints ?? []).filter(
      (uc) => (uc.fields ?? []).length > 1,
    );
    const actualUniqueBySig = new Map(
      actualUniques.map((uc) => [columnSignature(uc.fields), uc]),
    );
    const desiredUniqueSigs = new Set(
      desiredUniques.map((uc) => columnSignature(uc.fields)),
    );
    for (const uc of desiredUniques) {
      const sig = columnSignature(uc.fields);
      if (!actualUniqueBySig.has(sig)) {
        const cname = uc.name ?? `${name}_${uc.fields.join("_")}_key`;
        push(
          "unique",
          `add unique ${name}(${uc.fields.join(", ")})`,
          `ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(cname)} UNIQUE (${quoteList(
            uc.fields,
          )});`,
        );
      }
    }
    if (includeDrops) {
      for (const uc of actualUniques) {
        if (desiredUniqueSigs.has(columnSignature(uc.fields))) continue;
        push(
          "unique",
          `drop unique ${name}(${uc.fields.join(", ")})`,
          `ALTER TABLE ${q(name)} DROP CONSTRAINT IF EXISTS ${q(uc.name)};`,
          true,
        );
      }
    }

    // CHECK constraints
    const actualChecks = (catalog.checks ?? []).filter(
      (check) => check.table === name,
    );
    const desiredChecks = desiredCheckEntries(table, actualTable);
    const takenCheckNames = new Set(actualChecks.map((check) => check.name));
    const matchedChecks = new Set();
    for (const wanted of desiredChecks) {
      let index = actualChecks.findIndex(
        (check, i) =>
          !matchedChecks.has(i) &&
          normalizeCheckExpression(check.expression) === wanted.normalized,
      );
      if (index === -1 && wanted.name) {
        index = actualChecks.findIndex(
          (check, i) => !matchedChecks.has(i) && check.name === wanted.name,
        );
      }
      if (index === -1) {
        // A check may have been edited after it was imported; introspection
        // attaches it to the first column it references.
        const candidates = actualChecks
          .map((check, i) => ({ check, i }))
          .filter(
            ({ check, i }) =>
              !matchedChecks.has(i) &&
              (check.columns ?? [])[0] === wanted.column,
          );
        if (candidates.length === 1) {
          index = candidates[0].i;
        } else if (candidates.length > 1) {
          // Importing a column with several checks combines them with AND.
          // Recognise that combination so it is not re-added as a duplicate.
          const combined = candidates
            .map(
              ({ check }) => `(${normalizeCheckExpression(check.expression)})`,
            )
            .join(" AND ");
          if (combined === wanted.normalized) {
            candidates.forEach(({ i }) => matchedChecks.add(i));
            continue;
          }
        }
      }

      if (index === -1) {
        const constraintName = uniqueCheckName(
          wanted.name || `${name}_${wanted.column}_check`,
          takenCheckNames,
        );
        push(
          "check",
          `add check ${name}.${wanted.column}`,
          `ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(
            constraintName,
          )} CHECK (${wanted.expression});`,
        );
        continue;
      }

      const actualCheck = actualChecks[index];
      matchedChecks.add(index);
      if (
        normalizeCheckExpression(actualCheck.expression) === wanted.normalized
      ) {
        continue;
      }
      takenCheckNames.delete(actualCheck.name);
      const constraintName = uniqueCheckName(
        wanted.name || actualCheck.name,
        takenCheckNames,
      );
      push(
        "check",
        `update check ${name}.${wanted.column}`,
        `ALTER TABLE ${q(name)} DROP CONSTRAINT IF EXISTS ${q(
          actualCheck.name,
        )};\nALTER TABLE ${q(name)} ADD CONSTRAINT ${q(
          constraintName,
        )} CHECK (${wanted.expression});`,
      );
    }
    if (includeDrops) {
      actualChecks.forEach((check, index) => {
        if (matchedChecks.has(index)) return;
        push(
          "check",
          `drop check ${name}.${check.name}`,
          `ALTER TABLE ${q(name)} DROP CONSTRAINT IF EXISTS ${q(check.name)};`,
          true,
        );
      });
    }

    // Indexes
    const desiredIndexes = new Map(
      (table.indices ?? []).map((i) => [i.name, i]),
    );
    const constraintBacked = new Set(
      (catalog.uniques ?? [])
        .filter((u) => u.table === name)
        .map((u) => u.name),
    );
    const actualIndexes = (catalog.indexes ?? [])
      .filter((ix) => ix.table === name)
      .filter((ix) => !constraintBacked.has(ix.name));
    const actualIndexByName = new Map(actualIndexes.map((ix) => [ix.name, ix]));

    for (const [iname, index] of desiredIndexes) {
      const aix = actualIndexByName.get(iname);
      if (!aix) {
        push("index", `create index ${iname}`, createIndexSql(name, index));
      } else {
        const sameUnique = Boolean(aix.unique) === Boolean(index.unique);
        const sameCols =
          (aix.columns ?? []).join(",") === (index.fields ?? []).join(",");
        if (!sameUnique || !sameCols) {
          push(
            "index",
            `recreate index ${iname}`,
            `DROP INDEX IF EXISTS ${q(iname)};\n${createIndexSql(name, index)}`,
          );
        }
      }
    }
    if (includeDrops) {
      for (const aix of actualIndexes) {
        if (!desiredIndexes.has(aix.name)) {
          push(
            "index",
            `drop index ${aix.name}`,
            `DROP INDEX IF EXISTS ${q(aix.name)};`,
            true,
          );
        }
      }
    }
  }

  if (includeDrops) {
    for (const [name] of actualTables) {
      if (!desiredTables.has(name)) {
        push(
          "table",
          `drop table ${name}`,
          `DROP TABLE IF EXISTS ${q(name)} CASCADE;`,
          true,
        );
      }
    }
  }

  // ---- Foreign keys ----
  const tableById = new Map((desired.tables ?? []).map((t) => [t.id, t]));
  const desiredFk = new Map();
  for (const r of desired.relationships ?? []) {
    const start = tableById.get(r.startTableId);
    const end = tableById.get(r.endTableId);
    if (!start || !end) continue;
    const { startColumns, endColumns } = getFkColumnNames(r, start, end);
    if (startColumns.some((c) => !c) || endColumns.some((c) => !c)) continue;
    const sig = fkSignature("", start.name, startColumns, end.name, endColumns);
    desiredFk.set(sig, { r, start, end, startColumns, endColumns });
  }

  const actualFkList = (catalog.foreignKeys ?? []).map((fk) => ({
    sig: fkSignature("", fk.table, fk.columns, fk.refTable, fk.refColumns),
    name: fk.name,
    fk,
  }));
  const actualFkBySig = new Map(actualFkList.map((x) => [x.sig, x]));

  for (const [sig, entry] of desiredFk) {
    if (actualFkBySig.has(sig)) continue;
    const update = (entry.r.updateConstraint || "NO ACTION").toUpperCase();
    const del = (entry.r.deleteConstraint || "NO ACTION").toUpperCase();
    push(
      "foreign_key",
      `add foreign key ${entry.start.name}(${entry.startColumns.join(", ")})`,
      `ALTER TABLE ${q(entry.start.name)} ADD FOREIGN KEY (${quoteList(
        entry.startColumns,
      )}) REFERENCES ${q(entry.end.name)} (${quoteList(entry.endColumns)}) ON UPDATE ${update} ON DELETE ${del};`,
    );
  }
  if (includeDrops) {
    for (const x of actualFkList) {
      if (desiredFk.has(x.sig)) continue;
      push(
        "foreign_key",
        `drop foreign key ${x.fk.table}(${x.fk.columns.join(", ")})`,
        `ALTER TABLE ${q(x.fk.table)} DROP CONSTRAINT IF EXISTS ${q(x.name)};`,
        true,
      );
    }
  }

  const summary = {};
  for (const op of operations) {
    summary[op.group] = (summary[op.group] ?? 0) + 1;
  }

  const sql = operations.map((op) => op.sql).join("\n");

  return {
    operations,
    sql,
    summary,
    hasChanges: operations.length > 0,
    hasDestructive: operations.some((op) => op.destructive),
  };
}
