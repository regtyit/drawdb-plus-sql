import { DB } from "../../data/constants";
import { catalogToDiagram } from "./introspect";
import { exportSQL } from "../exportSQL";
import { quoteIdent } from "./sqlTemplates/value";

/**
 * Serialize a value coming from a pg result row into a SQL literal.
 * JSON values are written as jsonb literals, array columns as ARRAY[...].
 */
export function serializeSqlValue(value, column) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "number" && Number.isFinite(value)) {
    return String(value);
  }
  if (column?.isArray && Array.isArray(value)) {
    const items = value
      .map((item) =>
        typeof item === "number" && Number.isFinite(item)
          ? String(item)
          : `'${String(item).replace(/'/g, "''")}'`,
      )
      .join(", ");
    return `ARRAY[${items}]`;
  }
  if (typeof value === "object") {
    const json = JSON.stringify(value).replace(/'/g, "''");
    return `'${json}'::jsonb`;
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function qualifiedTableName(table) {
  return `${quoteIdent(table.schema ?? "public")}.${quoteIdent(table.name)}`;
}

export function generateInsertStatements(table, rows) {
  const columns = (table.columns ?? [])
    .map((column) => column.name)
    .filter(Boolean);
  if (!columns.length || !rows.length) return [];
  const byName = new Map((table.columns ?? []).map((c) => [c.name, c]));
  const target = quoteIdent(table.name);
  const columnList = columns.map(quoteIdent).join(", ");
  return rows.map(
    (row) =>
      `INSERT INTO ${target} (${columnList}) VALUES (${columns
        .map((name) => serializeSqlValue(row?.[name], byName.get(name)))
        .join(", ")});`,
  );
}

/**
 * CREATE TABLE / type statements that mirror the connected database,
 * so they can bootstrap an empty one.
 */
export function buildInitScript({
  catalog,
  rowsByTable = {},
  includeData = true,
}) {
  const mirror = { ...catalogToDiagram(catalog), database: DB.POSTGRES };
  mirror.references = mirror.relationships ?? [];
  const createSql = exportSQL(mirror);

  const insertStatements = [];
  if (includeData) {
    for (const table of catalog.tables ?? []) {
      const rows = rowsByTable[`${table.schema}.${table.name}`] ?? [];
      insertStatements.push(...generateInsertStatements(table, rows));
    }
  }

  return {
    createSql: createSql.trim(),
    insertSql: insertStatements.join("\n"),
  };
}

export function composeFullScript({
  initSql,
  insertSql,
  operationSql,
  rowsPerTable = 0,
  includeOperations = true,
}) {
  const sections = [];
  sections.push(
    `-- ============================================================\n-- Full SQL script generated by drawdb-plus-sql\n-- Run this on a fresh PostgreSQL database to rebuild it.\n-- ============================================================`,
  );
  if (initSql) {
    sections.push(
      `-- -------- 1. Table initialization (mirrored from the connected database) --------\n${initSql}`,
    );
  }
  if (insertSql) {
    sections.push(
      `-- -------- 2. Seed data (up to ${rowsPerTable} latest rows per table) --------\n${insertSql}`,
    );
  }
  if (includeOperations && operationSql?.trim()) {
    sections.push(
      `-- -------- 3. Pending diagram operations (diagram vs database) --------\n${operationSql.trim()}`,
    );
  }
  return sections.join("\n\n");
}
